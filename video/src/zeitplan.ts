export const FPS = 30;
export const INTRO = 4 * FPS;
export const OUTRO = 5 * FPS;
/** Voice starts shortly after a section begins and gets some air afterwards. */
export const STIMME_VORLAUF = Math.round(0.5 * FPS);
export const STIMME_NACHLAUF = Math.round(0.7 * FPS);
/** Recording size (Playwright viewport). */
export const AUFNAHME = { breite: 1600, hoehe: 900 };
export const HANDY = { breite: 390, hoehe: 844 };

export type Szene = { datei: string; dauer: number; marken: Record<string, number>; handy?: boolean };
export type Szenen = Record<string, Szene>;

export type Stimme = { datei: string; dauer: number; text: string };
export type Ton = { musik?: string; stimmen: Record<string, Stimme> };

export type Kapitel = {
  szene: string;
  bereich: string;
  titel: string;
  /** Voice-over, starts with the chapter. */
  sprecher: string;
  /** Bullet points next to the phone (only for phone scenes). */
  punkte?: string[];
};

export type Drehbuch = {
  id: string;
  /** Subfolder in public/ for recordings and audio, e.g. "details/" (empty = public/ itself). */
  ordner: string;
  /** Optional badge above the title in the intro, e.g. "Im Detail". */
  kicker?: string;
  untertitel: string;
  sprecherIntro: string;
  sprecherOutro: string;
  outroPunkte: string[];
  kapitel: Kapitel[];
};

/** All voice-over texts by key, as generated by `ton/vertonen.mjs`. */
export const sprechertexte = (d: Drehbuch): Record<string, string> => ({
  intro: d.sprecherIntro,
  ...Object.fromEntries(d.kapitel.map((k) => [k.szene, k.sprecher])),
  outro: d.sprecherOutro,
});

const mitStimme = (ton: Ton | undefined, schluessel: string) => {
  const s = ton?.stimmen[schluessel];
  return s ? STIMME_VORLAUF + Math.ceil(s.dauer * FPS) + STIMME_NACHLAUF : 0;
};

export const introFrames = (ton?: Ton) => Math.max(INTRO, mitStimme(ton, "intro"));
export const outroFrames = (ton?: Ton) => Math.max(OUTRO, mitStimme(ton, "outro"));
export const aufnahmeFrames = (s: Szene) => Math.round(s.dauer * FPS);
export const kapitelFrames = (k: Kapitel, s: Szene, ton?: Ton) => Math.max(aufnahmeFrames(s), mitStimme(ton, k.szene));

export const gesamtFrames = (d: Drehbuch, szenen: Szenen, ton?: Ton) =>
  introFrames(ton) + outroFrames(ton) + d.kapitel.filter((k) => szenen[k.szene]).reduce((summe, k) => summe + kapitelFrames(k, szenen[k.szene], ton), 0);
